CREATE TABLE IF NOT EXISTS storage_root_governed_groups (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  storage_root_id BIGINT UNSIGNED NOT NULL,
  identity_source_id BIGINT UNSIGNED NULL,
  permission_level VARCHAR(32) NOT NULL,
  group_dn VARCHAR(512) NULL,
  group_sid VARCHAR(190) NULL,
  group_sam_account_name VARCHAR(255) NULL,
  group_display_name VARCHAR(255) NULL,
  managed_by VARCHAR(32) NOT NULL DEFAULT 'borntoshare',
  provisioning_status VARCHAR(32) NOT NULL DEFAULT 'pending',
  is_active TINYINT(1) NOT NULL DEFAULT 1,
  created_from VARCHAR(64) NOT NULL DEFAULT 'manual',
  metadata_json JSON NULL,
  last_verified_at DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT fk_srg_storage_root_id FOREIGN KEY (storage_root_id) REFERENCES storage_roots(id) ON DELETE CASCADE,
  CONSTRAINT fk_srg_identity_source_id FOREIGN KEY (identity_source_id) REFERENCES identity_sources(id) ON DELETE SET NULL,
  KEY idx_srg_root_level (storage_root_id, permission_level),
  KEY idx_srg_identity_source (identity_source_id),
  KEY idx_srg_group_sid (group_sid),
  KEY idx_srg_group_sam (group_sam_account_name)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
