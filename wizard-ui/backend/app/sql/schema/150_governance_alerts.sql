CREATE TABLE IF NOT EXISTS governance_alerts (
  id BIGINT UNSIGNED PRIMARY KEY AUTO_INCREMENT,
  alert_key VARCHAR(190) NOT NULL,
  scope_type VARCHAR(64) NOT NULL,
  scope_id BIGINT UNSIGNED NOT NULL,
  alert_type VARCHAR(80) NOT NULL,
  severity VARCHAR(20) NOT NULL DEFAULT 'warning',
  status VARCHAR(20) NOT NULL DEFAULT 'open',
  title VARCHAR(190) NOT NULL,
  message TEXT NULL,
  source_type VARCHAR(80) NULL,
  source_id VARCHAR(190) NULL,
  zone_id BIGINT UNSIGNED NULL,
  storage_endpoint_id BIGINT UNSIGNED NULL,
  storage_root_id BIGINT UNSIGNED NULL,
  identity_source_id BIGINT UNSIGNED NULL,
  correlation_id VARCHAR(128) NULL,
  first_seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_seen_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  resolved_at DATETIME NULL,
  acknowledged_at DATETIME NULL,
  acknowledged_by BIGINT UNSIGNED NULL,
  metadata_json JSON NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  CONSTRAINT uq_governance_alerts_alert_key UNIQUE (alert_key),
  CONSTRAINT fk_governance_alerts_zone_id FOREIGN KEY (zone_id) REFERENCES zones(id) ON DELETE SET NULL,
  CONSTRAINT fk_governance_alerts_storage_endpoint_id FOREIGN KEY (storage_endpoint_id) REFERENCES storage_endpoints(id) ON DELETE SET NULL,
  CONSTRAINT fk_governance_alerts_storage_root_id FOREIGN KEY (storage_root_id) REFERENCES storage_roots(id) ON DELETE CASCADE,
  CONSTRAINT fk_governance_alerts_identity_source_id FOREIGN KEY (identity_source_id) REFERENCES identity_sources(id) ON DELETE SET NULL,
  CONSTRAINT fk_governance_alerts_acknowledged_by FOREIGN KEY (acknowledged_by) REFERENCES identities(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
